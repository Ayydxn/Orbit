package me.ayydxn.orbit.natives.generator;

import me.ayydxn.orbit.natives.generator.annotations.*;

import java.io.IOException;
import java.lang.reflect.AnnotatedElement;
import java.lang.reflect.Method;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;
import java.util.stream.Collectors;

public final class NativeBindingGenerator
{
    private static final String CONTRACT_PACKAGE_MARKER = ".natives.";
    private static final String JNI_PACKAGE_MARKER = ".natives.jni.";

    public static void main(String[] args) throws Exception
    {
        Path javaOut = Path.of(args[0]);
        Path cppOut = Path.of(args[1]);

        List<Contract> contracts = new ArrayList<>();
        for (int i = 2; i < args.length; i++)
            contracts.add(read(Class.forName(args[i])));

        contracts.sort(Comparator.comparing(Contract::name));

        for (Contract contract : contracts)
        {
            write(javaOut.resolve(contract.jniQualified().replace('.', '/') + ".java"), jniJava(contract));
            write(cppOut.resolve("ultralight/" + contract.baseName() + ".h"), cppHeader(contract));
            write(cppOut.resolve("ultralight/" + contract.baseName() + ".cpp"), cppSource(contract));
        }

        write(cppOut.resolve("GeneratedNativeInterfaces.h"), registryHeader(contracts));
    }

    private static Contract read(Class<?> type)
    {
        NativeContract annotation = type.getAnnotation(NativeContract.class);
        require(annotation != null, type + " is missing @NativeContract");

        List<Function> functions = Arrays.stream(type.getMethods())
                .filter(m -> m.isAnnotationPresent(NativeFunction.class))
                .sorted(Comparator.comparing(m -> m.getAnnotation(NativeFunction.class).value()))
                .map(NativeBindingGenerator::function)
                .toList();

        return new Contract(type, annotation.headers(), functions);
    }

    private static Function function(Method method)
    {
        NativeFunction annotation = method.getAnnotation(NativeFunction.class);

        List<Param> params = Arrays.stream(method.getParameters())
                .map(p ->
                {
                    require(p.isNamePresent(), "Compile the contracts with -parameters");
                    return new Param(p.getName(), type(p.getType(), p, annotation.custom(), method));
                })
                .toList();

        return new Function(method.getName(), annotation.value(), annotation.custom(), type(method.getReturnType(), method, annotation.custom(), method), params);
    }

    private static Type type(Class<?> javaType, AnnotatedElement source, boolean custom, Method owner)
    {
        Kind kind = javaType == void.class ? Kind.VOID
                : javaType == int.class ? Kind.INT
                : javaType == long.class ? Kind.LONG
                : javaType == boolean.class ? Kind.BOOLEAN
                : javaType == String.class ? Kind.STRING
                : null;

        require(kind != null, "Unsupported type " + javaType.getName() + " on " + owner);

        NativePointer nativePointer = source.getAnnotation(NativePointer.class);
        NativeType nativeType = source.getAnnotation(NativeType.class);
        UltralightString ulString = source.getAnnotation(UltralightString.class);

        require(nativePointer == null || kind == Kind.LONG, "@Ptr needs a long on " + owner);
        require(kind != Kind.STRING || custom || source.isAnnotationPresent(NativeString.class) || ulString != null,
                "String on " + owner + " needs @CString, @UltralightString or custom = true");

        return new Type(kind, nativePointer != null ? nativePointer.value() : null, nativeType != null ? nativeType.value() : null,
                ulString != null, ulString != null && ulString.owned(), source.isAnnotationPresent(NativeString.class));
    }

    private static String jniJava(Contract contract)
    {
        StringBuilder sb = new StringBuilder();

        sb.append("// GENERATED by NativeBindingGenerator from ").append(contract.name()).append(". DO NOT EDIT.\n");
        sb.append("package ").append(contract.jniPackage()).append(";\n\n");
        sb.append("import ").append(contract.type().getName()).append(";\n\n");
        sb.append("public final class ").append(contract.jniSimpleName()).append(" implements ").append(contract.name()).append("\n{\n");

        for (Function f : contract.functions())
        {
            String args = f.params().stream().map(Param::javaName).collect(Collectors.joining(", "));
            String call = "NativeMethods." + f.nativeName() + "(" + args + ");";

            sb.append("    @Override\n    public ").append(f.returnType().kind().javaType).append(' ').append(f.javaName())
                    .append('(').append(javaParams(f)).append(")\n    {\n        ")
                    .append(f.returnType().kind() == Kind.VOID ? "" : "return ").append(call).append("\n    }\n\n");
        }

        sb.append("    private static final class NativeMethods\n    {\n");
        for (Function f : contract.functions())
        {
            sb.append("        private static native ").append(f.returnType().kind().javaType).append(' ')
                    .append(f.nativeName()).append('(').append(javaParams(f)).append(");\n\n");
        }

        sb.setLength(sb.length() - 1);
        return sb.append("    }\n}\n").toString();
    }

    private static String javaParams(Function f)
    {
        return f.params().stream().map(p -> p.type().kind().javaType + " " + p.javaName()).collect(Collectors.joining(", "));
    }

    private static String cppHeader(Contract contract)
    {
        return """
                // GENERATED by NativeBindingGenerator from %1$s. DO NOT EDIT.
                #pragma once

                #include "core/NativeInterface.h"

                class %2$s : public INativeInterface
                {
                public:
                    ~%2$s() override = default;

                    const char* GetClassName() const override;
                    const std::vector<JNINativeMethod> GetNativeMethods() const override;
                };
                """.formatted(contract.name(), contract.cppClass());
    }

    private static String cppSource(Contract contract)
    {
        StringBuilder sb = new StringBuilder();

        sb.append("// GENERATED by NativeBindingGenerator from ").append(contract.name()).append(". DO NOT EDIT.\n");
        sb.append("#include \"").append(contract.baseName()).append(".h\"\n#include \"utils/JNIUtils.h\"\n\n");
        for (String header : contract.headers())
            sb.append("#include <").append(header).append(">\n");
        sb.append('\n');

        List<Function> custom = contract.functions().stream().filter(Function::custom).toList();
        for (Function f : custom)
            sb.append(cppSignature(f)).append(";\n");
        if (!custom.isEmpty())
            sb.append('\n');

        sb.append("namespace\n{\n");
        List<Function> generated = contract.functions().stream().filter(f -> !f.custom()).toList();
        for (int i = 0; i < generated.size(); i++)
        {
            sb.append(cppFunction(contract, generated.get(i)));
            sb.append(i + 1 < generated.size() ? "\n" : "");
        }
        sb.append("}\n\n");

        sb.append("const char* ").append(contract.cppClass()).append("::GetClassName() const\n{\n    return \"")
                .append(contract.jniInternalName()).append("\";\n}\n\n");

        sb.append("const std::vector<JNINativeMethod> ").append(contract.cppClass()).append("::GetNativeMethods() const\n{\n    return\n    {\n");
        for (int i = 0; i < contract.functions().size(); i++)
        {
            Function f = contract.functions().get(i);
            sb.append("        CJNIUtils::MakeNativeMethod(\"%s\", \"%s\", %s)%s\n"
                    .formatted(f.nativeName(), f.signature(), f.cppName(), i + 1 < contract.functions().size() ? "," : ""));
        }
        sb.append("    };\n}\n");

        return sb.toString();
    }

    private static String cppSignature(Function f)
    {
        boolean usesEnvironment = f.custom() || f.returnType().kind() == Kind.STRING;
        String params = f.params().stream()
                .map(p -> p.type().kind().jniType + " " + p.cppName())
                .collect(Collectors.joining(", "));

        return "%s JNICALL %s(JNIEnv*%s, jclass%s)".formatted(f.returnType().kind().jniType, f.cppName(),
                usesEnvironment ? " Environment" : "", params.isEmpty() ? "" : ", " + params);
    }

    private static String cppFunction(Contract contract, Function f)
    {
        StringBuilder sb = new StringBuilder();

        sb.append("    /*\n     * Class:     ").append(contract.bannerName()).append("\n")
                .append("     * Method:    ").append(f.nativeName()).append("\n")
                .append("     * Signature: ").append(f.signature()).append("\n     */\n");
        sb.append("    ").append(cppSignature(f)).append("\n    {\n");

        String args = f.params().stream().map(NativeBindingGenerator::cppArgument).collect(Collectors.joining(", "));
        String call = f.cName() + "(" + args + ")";
        Type returnType = f.returnType();

        if (returnType.kind() == Kind.VOID)
            sb.append("        ").append(call).append(";\n");
        else if (returnType.ptrType() != null)
            sb.append("        return reinterpret_cast<jlong>(").append(call).append(");\n");
        else if (returnType.cString())
            sb.append("        return Environment->NewStringUTF(").append(call).append(");\n");
        else if (returnType.ulString())
        {
            sb.append("        const ULString Result = ").append(call).append(";\n");
            sb.append("        if (!Result)\n            return nullptr;\n\n");
            sb.append("        const jstring JavaString = CJNIUtils::ToJavaString(Environment, Result);\n");
            if (returnType.ownedULString())
                sb.append("        ulDestroyString(Result);\n");
            sb.append("\n        return JavaString;\n");
        }
        else
            sb.append("        return static_cast<").append(returnType.kind().jniType).append(">(").append(call).append(");\n");

        return sb.append("    }\n").toString();
    }

    private static String cppArgument(Param p)
    {
        Type type = p.type();

        if (type.ptrType() != null)
            return "reinterpret_cast<" + type.ptrType() + ">(" + p.cppName() + ")";
        if (type.cType() != null)
            return "static_cast<" + type.cType() + ">(" + p.cppName() + ")";
        if (type.kind() == Kind.BOOLEAN)
            return "static_cast<bool>(" + p.cppName() + ")";

        return p.cppName();
    }

    private static String registryHeader(List<Contract> contracts)
    {
        StringBuilder sb = new StringBuilder();

        sb.append("// GENERATED by NativeBindingGenerator. DO NOT EDIT.\n#pragma once\n\n#include \"core/NativeInterfaceRegistry.h\"\n\n");
        for (Contract contract : contracts)
            sb.append("#include \"ultralight/").append(contract.baseName()).append(".h\"\n");

        sb.append("\n#include <memory>\n\ninline void AddGeneratedNativeInterfaces(CNativeInterfaceRegistry& Registry)\n{\n");
        for (Contract contract : contracts)
            sb.append("    Registry.Add(std::make_shared<").append(contract.cppClass()).append(">());\n");

        return sb.append("}\n").toString();
    }

    private static void require(boolean condition, String message)
    {
        if (!condition)
            throw new IllegalArgumentException(message);
    }

    private static void write(Path path, String content) throws IOException
    {
        Files.createDirectories(path.getParent());
        Files.writeString(path, content);
    }

    private record Type(Kind kind, String ptrType, String cType, boolean ulString, boolean ownedULString, boolean cString) {}

    private record Param(String javaName, Type type)
    {
        String cppName()
        {
            String pascal = Character.toUpperCase(javaName.charAt(0)) + javaName.substring(1);
            return type.kind() == Kind.BOOLEAN ? "b" + pascal : pascal;
        }
    }

    private record Function(String javaName, String cName, boolean custom, Type returnType, List<Param> params)
    {
        String nativeName() { return "n" + cName; }
        String cppName() { return "UL" + cName.substring(2) + "_Native"; }
        String signature()
        {
            return "(" + params.stream().map(p -> p.type().kind().jniSignature).collect(Collectors.joining()) + ")" + returnType.kind().jniSignature;
        }
    }

    private record Contract(Class<?> type, String[] headers, List<Function> functions)
    {
        String name() { return type.getSimpleName(); }
        String baseName() { return name().substring(0, name().length() - "Natives".length()); }
        String cppClass() { return "C" + baseName(); }
        String jniSimpleName() { return "JNI" + name(); }
        String jniPackage() { return type.getPackageName().replace(CONTRACT_PACKAGE_MARKER, JNI_PACKAGE_MARKER); }
        String jniQualified() { return jniPackage() + "." + jniSimpleName(); }
        String jniInternalName() { return jniQualified().replace('.', '/') + "$NativeMethods"; }
        String bannerName() { return jniQualified().replace('.', '_') + "_NativeMethods"; }
    }

    private enum Kind
    {
        VOID("void", "void", "V"),
        INT("int", "jint", "I"),
        LONG("long", "jlong", "J"),
        BOOLEAN("boolean", "jboolean", "Z"),
        STRING("String", "jstring", "Ljava/lang/String;");

        final String javaType;
        final String jniType;
        final String jniSignature;

        Kind(String javaType, String jniType, String jniSignature)
        {
            this.javaType = javaType;
            this.jniType = jniType;
            this.jniSignature = jniSignature;
        }
    }
}
